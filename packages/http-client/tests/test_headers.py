from assertpy import assert_that
from http_client import options
from http_client.event_hooks import REQUEST_ID_HEADER, TRACEPARENT_HEADER
from httpx import codes
from pytest_httpx import HTTPXMock

from .support.clients import SyncClientFactory

UUID_PATTERN = r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"
TRACEPARENT_PATTERN = r"^00-[0-9a-f]{32}-[0-9a-f]{16}-01$"


def test_default_header_applies_when_call_has_none(httpx_mock: HTTPXMock, new_client: SyncClientFactory) -> None:
    """Заголовок по умолчанию подставляется, если в вызове его нет."""
    httpx_mock.add_response(status_code=codes.OK)
    client = new_client("https://example.com", options.with_default_headers({"X-Tenant": "default"}))

    client.get("/api/test")

    assert_that(httpx_mock.get_requests()[0].headers["X-Tenant"]).is_equal_to("default")


def test_call_header_wins_over_default(httpx_mock: HTTPXMock, new_client: SyncClientFactory) -> None:
    """Заголовок, переданный в вызов, не перетирается заголовком по умолчанию.

    Регрессия: хук делал headers.update(), и default побеждал per-request,
    что противоположно семантике httpx.
    """
    httpx_mock.add_response(status_code=codes.OK)
    client = new_client("https://example.com", options.with_default_headers({"X-Tenant": "default"}))

    client.get("/api/test", headers={"X-Tenant": "explicit"})

    assert_that(httpx_mock.get_requests()[0].headers["X-Tenant"]).is_equal_to("explicit")


def test_all_default_headers_apply(httpx_mock: HTTPXMock, new_client: SyncClientFactory) -> None:
    """В запрос попадает каждый заголовок из набора по умолчанию."""
    region: dict[str, str] = {"X-Region": "ru-central-1"}
    client_name: dict[str, str] = {"X-Client": "orders-bot"}
    httpx_mock.add_response(status_code=codes.OK)
    client = new_client("https://example.com", options.with_default_headers(region | client_name))

    client.get("/api/test")

    assert_that(httpx_mock.get_requests()[0].headers).contains_entry(region, client_name)


def test_generates_request_id_header(httpx_mock: HTTPXMock, new_client: SyncClientFactory) -> None:
    """Клиент проставляет запросу идентификатор в виде UUID."""
    httpx_mock.add_response(status_code=codes.OK)
    client = new_client("https://example.com", options.with_autogenerated_request_id())

    client.get("/api/test")

    assert_that(httpx_mock.get_requests()[0].headers[REQUEST_ID_HEADER]).matches(UUID_PATTERN)


def test_generates_own_request_id_for_every_request(httpx_mock: HTTPXMock, new_client: SyncClientFactory) -> None:
    """Каждый запрос получает собственный идентификатор."""
    httpx_mock.add_response(status_code=codes.OK)
    httpx_mock.add_response(status_code=codes.OK)
    client = new_client("https://example.com", options.with_autogenerated_request_id())

    client.get("/api/first")
    client.get("/api/second")

    assert_that(
        [request.headers[REQUEST_ID_HEADER] for request in httpx_mock.get_requests()]
    ).does_not_contain_duplicates()


def test_keeps_request_id_when_same_request_is_sent_again(httpx_mock: HTTPXMock, new_client: SyncClientFactory) -> None:
    """Повторная отправка того же объекта запроса сохраняет идентификатор.

    На это опираются библиотеки повторных попыток: повтор шлёт тот же Request, и все попытки
    должны уходить под одним идентификатором.
    """
    httpx_mock.add_response(status_code=codes.OK)
    httpx_mock.add_response(status_code=codes.OK)
    client = new_client("https://example.com", options.with_autogenerated_request_id())
    request = client.client.build_request("GET", "/api/test")

    client.send(request)
    client.send(request)

    assert_that({request.headers[REQUEST_ID_HEADER] for request in httpx_mock.get_requests()}).is_length(1)


def test_keeps_request_id_supplied_by_caller(httpx_mock: HTTPXMock, new_client: SyncClientFactory) -> None:
    """Идентификатор, проставленный вызывающим кодом, не подменяется."""
    httpx_mock.add_response(status_code=codes.OK)
    client = new_client("https://example.com", options.with_autogenerated_request_id())

    client.get("/api/test", headers={REQUEST_ID_HEADER: "caller-owned-id"})

    assert_that(httpx_mock.get_requests()[0].headers[REQUEST_ID_HEADER]).is_equal_to("caller-owned-id")


