def with_logger(logger: Logger, **settings: Unpack[LoggingOptions]) -> ClientOption:
    """Set the logger for HTTP client requests and responses.

    :param logger: Logger
    :param sanitize_keys: Keys in [glom](https://glom.readthedocs.io/en/latest/) format
                          to mask sensitive data
    :param json_indent: JSON log indentation width (no indentation by default)
    :param use_line_breaks: Whether to add line breaks between request properties (disabled by default)
    :param log_level: HTTP client log level, INFO by default
    :param use_default_sanitize_keys: Whether to mask common secrets
                                      (see `DEFAULT_SANITIZE_KEYS`) in addition to `sanitize_keys`
    :returns: Option that sets the HTTP client logger and hooks
    """
    _reject_unknown_options(settings, LoggingOptions.__optional_keys__)
    sanitize_keys = settings.get("sanitize_keys")
    json_indent = settings.get("json_indent")
    use_line_breaks = settings.get("use_line_breaks")
    log_level = settings.get("log_level")
    use_default_sanitize_keys = settings.get("use_default_sanitize_keys", True)
    keys = list(sanitize_keys or [])
    if use_default_sanitize_keys:
        keys.extend(key for key in DEFAULT_SANITIZE_KEYS if key not in keys)

    def option(client: BaseHttpClient) -> None:
        client.add_request_hook(
            request_logger_hook(
                logger=logger,
                sanitize_keys=keys,
                json_indent=json_indent,
                use_line_breaks=use_line_breaks,
                log_level=log_level,
            )
        )
        build_response_hook = (
            async_response_logger_hook if isinstance(client, AsyncHttpClient) else response_logger_hook
        )
        client.add_response_hook(
            build_response_hook(
                logger=logger,
                sanitize_keys=keys,
                json_indent=json_indent,
                use_line_breaks=use_line_breaks,
                log_level=log_level,
            )
        )

    return option


