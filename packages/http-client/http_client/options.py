def with_verify_context(*, verify: ssl.SSLContext | str | bool) -> ClientOption:
    """Установить контекст проверки SSL сертификата для HTTPS соединения.

    ⚠️ `verify=False` полностью отключает проверку сертификата и делает соединение
    уязвимым к man-in-the-middle. Допустимо только для локальной отладки.

    :param verify: SSL контекст, путь к CA-сертификату или False для отключения проверки
    :returns: опция, которая применяется к HTTP-клиенту для установки контекста проверки сертификата
    """
    # httpx с 0.28 объявил строковый verify устаревшим, поэтому путь превращаем в контекст сами.
    context = ssl.create_default_context(cafile=verify) if isinstance(verify, str) else verify

    def option(client: BaseHttpClient) -> None:
        client.verify = context

    return option


def use_truststore() -> ClientOption:
    """Использовать системное хранилище SSL сертификатов для проверки HTTPS соединения.

    :raises ImportError: возникает, когда не установлен модуль truststore
    :return: опция для установки контекста проверки сертификата из системного хранилища.
    """
    try:
        truststore = importlib.import_module("truststore")

        context_factory = cast("Callable[[int], ssl.SSLContext]", truststore.SSLContext)
        ctx = context_factory(ssl.PROTOCOL_TLS_CLIENT)
        return with_verify_context(verify=ctx)
    except ImportError:
        message = "Для использования truststore установите cloudru-qa-http-client[truststore]"
        raise ImportError(message) from None


