def with_logger(logger: Logger, **settings: Unpack[LoggingOptions]) -> ClientOption:
    """Установить логгер для логирования запросов и ответов в HTTP-клиенте.

    :param logger: логгер
    :param sanitize_keys: ключи в формате [glom](https://glom.readthedocs.io/en/latest/)
                          для скрытия конфиденциальных данных
    :param json_indent: ширина отступа для логирования JSON свойств (по умолчанию отступ отсутствует)
    :param use_line_breaks: использовать ли переносы на новую строку между свойствами запроса (по умолчанию нет)
    :param log_level: уровень логов HTTP-клиент, по умолчанию INFO
    :param use_default_sanitize_keys: маскировать ли типовые секреты
                                      (см. `DEFAULT_SANITIZE_KEYS`) в дополнение к `sanitize_keys`
    :returns: опция, которая применяется к HTTP-клиенту для установки логгера и хуков
    """
    _reject_unknown_options(settings, LoggingOptions.__optional_keys__)
    sanitize_keys = settings.get("sanitize_keys")
    json_indent = settings.get("json_indent")
    use_line_breaks = settings.get("use_line_breaks")
    log_level = settings.get("log_level")
    use_default_sanitize_keys = settings.get("use_default_sanitize_keys", True)
    keys = list(sanitize_keys or [])
    if use_default_sanitize_keys:
        keys.extend(key for key in DEFAULT_SANITIZE_KEYS if key not in keys)

    def option(client: BaseHttpClient) -> None:
        client.add_request_hook(
            request_logger_hook(
                logger=logger,
                sanitize_keys=keys,
                json_indent=json_indent,
                use_line_breaks=use_line_breaks,
                log_level=log_level,
            )
        )
        build_response_hook = (
            async_response_logger_hook if isinstance(client, AsyncHttpClient) else response_logger_hook
        )
        client.add_response_hook(
            build_response_hook(
                logger=logger,
                sanitize_keys=keys,
                json_indent=json_indent,
                use_line_breaks=use_line_breaks,
                log_level=log_level,
            )
        )

    return option


