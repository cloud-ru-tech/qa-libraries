"""Идентификаторы запроса не должны меняться от попытки к попытке."""

import httpx
import pytest
from http_client import AsyncHttpClient, HttpClient
from http_client import options as http_options
from http_client_retries.options import with_retries_failed_requests, with_retries_if
from pytest_httpx import HTTPXMock

from tests.assertions import assert_that
from tests.fakes import CorrelationRecorder


def is_server_error(response: httpx.Response) -> bool:
    return response.status_code >= httpx.codes.INTERNAL_SERVER_ERROR


@pytest.mark.usefixtures("fast_retries")
def test_keeps_request_id_across_retries(httpx_mock: HTTPXMock) -> None:
    recorder = CorrelationRecorder(
        "X-Request-ID",
        httpx.ConnectError("upstream reset"),
        httpx.ConnectError("upstream reset"),
        httpx.Response(200),
    )
    httpx_mock.add_callback(recorder, is_reusable=True)

    with HttpClient(
        "https://orders.internal",
        http_options.with_autogenerated_request_id(),
        with_retries_failed_requests(),
    ) as client:
        client.send(httpx.Request("POST", "https://orders.internal/checkout"))

    assert_that(recorder.captured).is_same_across_attempts()


