@pytest.mark.usefixtures("fast_retries")
def test_gives_separate_requests_their_own_identifiers(httpx_mock: HTTPXMock) -> None:
    recorder = CorrelationRecorder("X-Request-ID", httpx.Response(200), httpx.Response(200))
    httpx_mock.add_callback(recorder, is_reusable=True)

    with HttpClient(
        "https://orders.internal",
        http_options.with_autogenerated_request_id(),
        with_retries_failed_requests(),
    ) as client:
        client.get("/first")
        client.get("/second")

    assert_that(set(recorder.captured)).is_length(2)
