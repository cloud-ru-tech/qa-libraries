import allure
import httpx
import pytest
from http_client import ClientOption, HttpClient, options
from http_client_allure import wrap_requests_in_steps
from http_client_retries import options as retry_options
from http_client_retries.config import RetryOverrides
from httpx import codes
from tenacity import RetryError, stop_after_attempt, wait_none

from .assertions import assert_that

pytestmark = allure.feature("Порядок опций")


def is_server_error(response: httpx.Response) -> bool:
    """Признак ответа, который стоит повторить."""
    return response.is_server_error


def build_retries(attempts: int) -> ClientOption:
    """Собрать опцию повторов без пауз между попытками.

    :param attempts: сколько раз запрос уйдет на сервер.
    :returns: опция повторов для конструктора клиента.
    """
    return retry_options.with_retries_if(
        is_server_error, overrides=RetryOverrides(stop=stop_after_attempt(attempts), wait=wait_none())
    )


@allure.title("Опция после ретраев прячет все повторы внутрь одного шага")
def test_hides_retries_inside_single_step(httpbin_url: str) -> None:
    client_options = (build_retries(3), wrap_requests_in_steps())

    with (
        HttpClient(httpbin_url, *client_options) as client,
        pytest.raises(RetryError) as failure,
    ):
        client.get("/status/500")

    assert_that(failure.value).kept_response_with_status(codes.INTERNAL_SERVER_ERROR)


@allure.title("Опция перед ретраями показывает каждую попытку своим шагом")
def test_shows_step_per_retry(httpbin_url: str) -> None:
    client_options = (wrap_requests_in_steps(), build_retries(3))

    with (
        HttpClient(httpbin_url, *client_options) as client,
        pytest.raises(RetryError) as failure,
    ):
        client.get("/status/503")

    assert_that(failure.value).kept_response_with_status(codes.SERVICE_UNAVAILABLE)


@allure.title("Заголовок из with_default_headers попадает в отчет")
def test_shows_default_header(httpbin_url: str) -> None:
    tenant = "retail"
    client_options = (options.with_default_headers({"x-tenant": tenant}), wrap_requests_in_steps())

    with HttpClient(httpbin_url, *client_options) as client:
        response = client.get("/headers")

    assert_that(response).echoes_header("x-tenant", [tenant])


@allure.title("Автоматический идентификатор запроса тоже виден в отчете")
def test_shows_autogenerated_request_id(httpbin_url: str) -> None:
    client_options = (options.with_autogenerated_request_id(), wrap_requests_in_steps())

    with HttpClient(httpbin_url, *client_options) as client:
        response = client.get("/headers")

    assert_that(response).carries_header("x-request-id")


@allure.title("Заголовок авторизации в отчете замаскирован")
def test_masks_authorization_added_by_option(httpbin_url: str) -> None:
    client_options = (options.with_auth(httpx.BasicAuth("cashier", "hunter2")), wrap_requests_in_steps())

    with HttpClient(httpbin_url, *client_options) as client:
        response = client.get("/basic-auth/cashier/hunter2")

    assert_that(response).has_json_field("authorized", expected=True)
