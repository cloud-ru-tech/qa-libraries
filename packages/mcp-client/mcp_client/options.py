"""Options receiving the actual MCP client."""

from __future__ import annotations

from secrets import randbelow
from typing import TYPE_CHECKING
from uuid import uuid4

from tenacity import retry, stop_after_attempt, wait_fixed

from .event_hooks import (
    create_request_logger_hook,
    create_request_structlogger_hook,
    create_response_logger_hook,
    create_response_structlogger_hook,
)

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence
    from logging import Logger

    from .client import BaseAsyncMCPClient, ClientOption
    from .custom_types import StructuredLogger


def with_read_timeout(timeout: float) -> ClientOption:
    """Set the default read timeout.

    :param timeout: Read timeout in seconds.
    :return: Client option.
    """

    def option(client: BaseAsyncMCPClient) -> None:
        client.read_timeout_seconds = timeout

    return option


def with_logger(logger: Logger, sanitize_keys: Sequence[str] | None = None) -> ClientOption:
    """Log requests and responses with sensitive keys masked.

    :param logger: Standard logger.
    :param sanitize_keys: Sensitive keys or literal text.
    :return: Client option.
    """

    def option(client: BaseAsyncMCPClient) -> None:
        client.add_request_hook(create_request_logger_hook(logger, sanitize_keys or ()))
        client.add_response_hook(create_response_logger_hook(logger, sanitize_keys or ()))

    return option


def with_structlogger(logger: StructuredLogger, sanitize_keys: Sequence[str] | None = None) -> ClientOption:
    """Log sanitized structured requests and responses.

    :param logger: Structured logger.
    :param sanitize_keys: Sensitive keys or literal text.
    :return: Client option.
    """

    def option(client: BaseAsyncMCPClient) -> None:
        client.add_request_hook(create_request_structlogger_hook(logger, sanitize_keys or ()))
        client.add_response_hook(create_response_structlogger_hook(logger, sanitize_keys or ()))

    return option


def _request_id_metadata() -> dict[str, object]:
    return {"x-request-id": str(uuid4())}


def _traceparent_metadata() -> dict[str, object]:
    trace_id = randbelow((1 << 128) - 1) + 1
    parent_id = randbelow((1 << 64) - 1) + 1
    return {"traceparent": f"00-{trace_id:032x}-{parent_id:016x}-01"}


def with_autogenerated_request_id() -> ClientOption:
    """Generate a fresh request UUID for each logical public request.

    Explicit and default identifiers take precedence; retries reuse the same UUID.

    :return: Client option registering request-ID generation.
    """

    def option(client: BaseAsyncMCPClient) -> None:
        client.add_metadata_provider(_request_id_metadata)

    return option


def with_autogenerated_traceparent() -> ClientOption:
    """Generate a valid W3C traceparent for each logical public request.

    Explicit and default trace contexts take precedence; retries reuse the value.

    :return: Client option registering trace-context generation.
    """

    def option(client: BaseAsyncMCPClient) -> None:
        client.add_metadata_provider(_traceparent_metadata)

    return option


def with_default_metadata(metadata: Mapping[str, object]) -> ClientOption:
    """Merge values into default request metadata.

    :param metadata: Default metadata.
    :return: Client option.
    """

    def option(client: BaseAsyncMCPClient) -> None:
        client.update_default_metadata(metadata)

    return option


def retry_if_tool_calling_fails(
    retries_attempts_number: int,
    retries_interval_in_seconds: float,
    *,
    reraise_exception: bool = False,
) -> ClientOption:
    """Retry raised tool-call errors.

    :param retries_attempts_number: Maximum number of attempts.
    :param retries_interval_in_seconds: Delay between attempts.
    :param reraise_exception: Propagate the final exception instead of RetryError.
    :return: Client option.
    """

    def option(client: BaseAsyncMCPClient) -> None:
        client.add_execute_decorator(
            retry(
                stop=stop_after_attempt(retries_attempts_number),
                wait=wait_fixed(retries_interval_in_seconds),
                reraise=reraise_exception,
            )
        )

    return option


def retry_if_connection_fails(
    retries_attempts_number: int,
    retries_interval_in_seconds: float,
    *,
    reraise_exception: bool = False,
) -> ClientOption:
    """Retry connection initialization errors.

    :param retries_attempts_number: Maximum number of attempts.
    :param retries_interval_in_seconds: Delay between attempts.
    :param reraise_exception: Propagate the final exception instead of RetryError.
    :return: Client option.
    """

    def option(client: BaseAsyncMCPClient) -> None:
        client.add_connect_decorator(
            retry(
                stop=stop_after_attempt(retries_attempts_number),
                wait=wait_fixed(retries_interval_in_seconds),
                reraise=reraise_exception,
            )
        )

    return option
