async def test_generates_uuid4_request_identifiers(connection_handler: ConnectionHandlerFactory) -> None:
    async with BaseAsyncMCPClient(connection_handler, with_autogenerated_request_id()) as client:
        result = await client.call_tool("echo_arguments_and_metadata_structured")
    assert_that(cast("dict[str, object]", result.metadata)["x-request-id"]).matches(
        r"^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$",
    )


