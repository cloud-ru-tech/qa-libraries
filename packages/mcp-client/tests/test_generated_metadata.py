@dataclass
class ObservedRequest:
    method: str
    metadata: Mapping[str, object]


@dataclass
class RecordingConnection:
    factory: ConnectionHandlerFactory
    requests: list[ObservedRequest] = field(default_factory=list)

    @asynccontextmanager
    async def __call__(self) -> AsyncIterator[Streams]:
        outgoing, received = anyio.create_memory_object_stream[SessionMessage](0)
        async with self.factory() as (reader, writer), outgoing, received, anyio.create_task_group() as group:
            group.start_soon(self._forward, received, writer)
            try:
                yield reader, outgoing
            finally:
                group.cancel_scope.cancel()

    def values(self, method: str, key: str) -> list[object]:
        return [request.metadata[key] for request in self.requests if request.method == method]

    async def _forward(
        self,
        source: MemoryObjectReceiveStream[SessionMessage],
        destination: MemoryObjectSendStream[SessionMessage],
    ) -> None:
        async for message in source:
            payload = cast("Mapping[str, object]", message.message.model_dump(mode="json", exclude_none=True))
            method = payload.get("method")
            if "id" in payload and isinstance(method, str):
                params = cast("Mapping[str, object]", payload.get("params", {}))
                metadata = cast("Mapping[str, object]", params.get("_meta", {}))
                self.requests.append(ObservedRequest(method, metadata))
            await destination.send(message)


async def request_twice(client: BaseAsyncMCPClient, method: str) -> None:
    if method == "tools/call":
        await client.call_tool("add", {"a": 13, "b": 19})
        await client.call_tool("add", {"a": 29, "b": 47})
    elif method == "tools/list":
        await client.list_tools()
        await client.list_tools()
    else:
        await client.ping_server()
        await client.ping_server()


@pytest.mark.parametrize("method", ["tools/call", "tools/list", "ping"])
async def test_generates_distinct_request_ids_for_public_calls(
    connection_handler: ConnectionHandlerFactory,
    method: str,
) -> None:
    connection = RecordingConnection(connection_handler)
    async with BaseAsyncMCPClient(connection, with_autogenerated_request_id()) as client:
        await request_twice(client, method)
    assert_that(connection.values(method, "x-request-id")).is_length(2).does_not_contain_duplicates()


